const P = "❤";

function pick() {
  return EMOJI_IDS[Math.floor(Math.random() * EMOJI_IDS.length)];
}

function withEmoji(text) {
  return {
    text: `${P} ${text}`,
    entities: [
      { type: "custom_emoji", offset: 0, length: P.length, custom_emoji_id: pick() },
    ],
  };
}

function withEmojiWrap(text) {
  const inner = `${P} ${text} ${P}`;
  const secondOffset = `${P} ${text} `.length;
  return {
    text: inner,
    entities: [
      { type: "custom_emoji", offset: 0,            length: P.length, custom_emoji_id: pick() },
      { type: "custom_emoji", offset: secondOffset, length: P.length, custom_emoji_id: pick() },
    ],
  };
}

